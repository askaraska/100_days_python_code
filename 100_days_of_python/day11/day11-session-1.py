############### Our Blackjack House Rules #####################

## using cards
## goal is to add up your cards to the largest number without going over 21
## if the card in your hand add up to more 21. then, it is called a bust. and ,it means 'you lose'.
## There are no jokers.
## all the cards from 2 to 10 count as their face value.
## 6 is 6 , 9 is 9
## The Jack/Queen/King all count as 10.
## special card - The the Ace can count as 11 or 1.
